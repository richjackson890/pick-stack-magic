-- 경력 서열. 작을수록 위. 팀원 정렬 2순위로 쓴다.
-- (1순위 직급 → 2순위 seniority → 3순위 이름 가나다순)
--
-- 이 값을 코드의 이름 배열(MEMBER_ORDER)로 들고 있었으나,
-- 신규 입사자가 들어올 때마다 코드를 고쳐야 하고 누락되면 정렬에서 맨 아래로 밀려
-- (원지연·유승권이 그 케이스) DB 컬럼으로 옮겼다.
--
-- 현재 팀원 10명의 값은 대시보드에서 직접 넣었고 여기에 담지 않는다.
-- 이름으로 매칭하는 백필이라 다른 환경(로컬·신규 프로젝트)에서는 맞지 않는다.
-- 값이 없으면(null) 같은 직급 안에서 맨 아래로 정렬될 뿐 동작에는 문제가 없다.

alter table public.profiles
  add column if not exists seniority int;
